const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.ITAM_UI_URL || 'http://127.0.0.1:5190';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const login = await page.request.post(base + '/api/auth/login', { data: { username: 'admin', password: process.env.ITAM_TEST_PASSWORD } });
    assert.equal(login.status(), 200);
    const jwt = (await login.json()).data.accessToken;
    await page.addInitScript(token => sessionStorage.setItem('itdesk.accessToken', token), jwt);
    await page.goto(base + '/admin/assets');
    await page.getByRole('heading', { name: 'Tài sản', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Thêm tài sản', exact: true }).click();
    const code = 'WEB-' + Date.now();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Mã tài sản', { exact: true }).fill(code);
    await dialog.getByLabel('Tên thiết bị', { exact: true }).fill('Laptop kiểm thử');
    await dialog.getByLabel('Loại thiết bị', { exact: true }).press('ArrowDown');
    await page.getByTitle('Máy tính xách tay', { exact: true }).click();
    await dialog.getByLabel('Serial', { exact: true }).fill('SN-123');
    await dialog.getByLabel('Vị trí', { exact: true }).fill('Phòng IT');
    await dialog.getByRole('button', { name: 'Lưu tài sản', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await page.getByPlaceholder('Mã, tên, serial', { exact: true }).fill(code);
    await page.getByPlaceholder('Mã, tên, serial', { exact: true }).press('Enter');
    const row = page.getByRole('row').filter({ hasText: code });
    await row.getByText('Sẵn sàng', { exact: true }).waitFor();
    await row.getByText('Máy tính xách tay', { exact: true }).waitFor();
    await row.getByRole('button', { name: 'Chi tiết / sửa', exact: true }).click();
    assert.equal(await dialog.getByLabel('Serial', { exact: true }).inputValue(), 'SN-123');
    await dialog.getByLabel('Vòng đời', { exact: true }).press('ArrowDown');
    await page.getByTitle('Bảo trì', { exact: true }).click();
    await dialog.getByLabel('Vị trí', { exact: true }).fill('Phòng bảo trì');
    await dialog.getByRole('button', { name: 'Lưu tài sản', exact: true }).click();
    await row.getByText('Bảo trì', { exact: true }).waitFor();
    await page.reload();
    await page.getByPlaceholder('Mã, tên, serial', { exact: true }).fill(code);
    await page.getByPlaceholder('Mã, tên, serial', { exact: true }).press('Enter');
    await row.getByText('Phòng bảo trì', { exact: true }).waitFor();
    await row.getByRole('button', { name: 'Chi tiết / sửa', exact: true }).click();
    await dialog.getByLabel('Vòng đời', { exact: true }).press('ArrowDown');
    await page.getByTitle('Ngừng sử dụng', { exact: true }).click();
    await dialog.getByRole('button', { name: 'Lưu tài sản', exact: true }).click();
    await row.getByText('Ngừng sử dụng', { exact: true }).waitFor();
    await row.getByRole('button', { name: 'Chi tiết / sửa', exact: true }).click();
    assert.equal(await dialog.getByLabel('Vòng đời', { exact: true }).isDisabled(), true);
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('heading', { name: 'Tài sản', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: '../docs/assets-mobile.png', fullPage: true, animations: 'disabled' });
    assert.deepEqual(errors, []);
    console.log('PASS: asset create/detail/search/update/reload/retire, terminal status UI and mobile layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
